// Regenerates the furniture and material catalogue in docs/SCHEMA.md (between the
// <!-- catalogue:start --> and <!-- catalogue:end --> markers) from the engine itself, so the
// documented sizes are always the ones the engine uses.   node scripts/catalogue.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { useProject, ROOT } from './lib/project.mjs';
useProject();
const { INFO, furnitureInfo } = await import('../engine/interior/furniture/index.js');
const { DRIVABLE } = await import('../engine/interior/furniture/vehicles.js');
const { MATERIAL_NAMES } = await import('../engine/materials.js');

// group by module (the order of the registry) with a one-line hint of the useful parameters
const HINT = {
  sofa: 'seats 2–4, fabric, pillow', sofaSectional: "corner 'left'|'right', depth, fabric", armchairWingback: 'fabric', armchairLounge: 'fabric, frame',
  coffeeTable: 'mat', diningTable: 'mat, round (w = diameter)', diningChair: 'fabric, mat', kitchenRun: "sink true|offset, cooktop true|offset, tall 'fridge'|'pantry', tallSide 'left'|'right', uppers, cabinet, top",
  kitchenIsland: 'cabinet, top, sink \'back\'', vanity: 'sinks 1–2, top', showerGlass: "sides ['front','left','right']", bed: "size 'single'|'queen'|'king'|'superking', headboard 'tufted'|'carved'|'sleigh'|'panel', frame, fabric",
  wardrobe: 'mat', bookcase: 'mat', rug: "mat 'rugJute'|'rugWoolNeutral'|'rugSage'|'rugPersianRed'|…", plantPot: "size 'small'|'medium'|'large'", wallArt: "art 'canvasArt1..3', z (centre height)",
  mirror: 'z', tv: 'z', tableLamp: 'z = height of the table top it stands on', dryer: 'stacked', deskExecutive: 'ret (L return), retSide', outdoorSofa: 'corner',
  wallCharger: 'z', lounger: 'fabric', umbrella: 'fabric',
};
const rows = [];
for (const type of Object.keys(INFO)) {
  if (DRIVABLE.has(type)) continue;
  const i = furnitureInfo(type, {});
  rows.push(`| \`${type}\` | ${i.w} × ${i.d} × ${i.h} | ${i.mount} | ${i.solid ? 'yes' : 'no'} | ${(HINT[type] || '').replaceAll('|', '\\|')} |`);
}
const cars = [...DRIVABLE].map(t => { const i = furnitureInfo(t, {}); return `| \`${t}\` | ${i.w} × ${i.d} × ${i.h} | color '#rrggbb' |`; });
const text = `<!-- catalogue:start -->
<!-- generated by scripts/catalogue.mjs: do not edit by hand -->
#### Furniture types (${rows.length})

Sizes are the defaults: width (along the item's front) × depth (front to back) × height, metres.
\`w\`, \`d\`, \`h\` in an item override them for most types. mount: floor (x, y = footprint centre) ·
wall (x, y = point on the inner wall face; rot points into the room) · ceiling (hangs from the
ceiling; x, y = the point below it). solid: blocks walking (a collider).

| type | w × d × h (m) | mount | solid | useful params |
|---|---|---|---|---|
${rows.join('\n')}

#### Drivable cars (${cars.length})

Put them in a garage room or a site area (e.g. the carport). They are driven with E (driver /
passenger), not merged into the furniture. Front = the car's nose.

| type | w × d × h (m) | params |
|---|---|---|
${cars.join('\n')}

#### Material names (${MATERIAL_NAMES.length} + floor / wall keys + colour factories)

Furniture params (\`mat\`, \`fabric\`, \`frame\`, \`top\`, \`cabinet\`) and finishes take these names:
${MATERIAL_NAMES.map(n => `\`${n}\``).join(', ')}.

Floors (\`finish.floor\`): \`wood\`, \`woodDark\`, \`woodHerringbone\`, \`woodPlankDark\`, \`travertine\`, \`travertineHoned\`,
\`marbleWhite\`, \`concretePolished\`, \`tileBath\`, \`tileGrey\`, \`concrete\`, \`epoxy\`, \`carpet\`, \`rubber\`, \`teak\`, \`oak\`.
Outside: \`pavers\`, \`paversWarm\`, \`gravel\`, \`asphalt\`, \`concrete\`, \`stone\`, \`teak\`. Roofs: \`terracotta\`,
\`roofTileDark\`, \`roofMetal\`, \`roofMetalLight\`, \`roofDeck\` (flat).
Colour factories: \`paint:#rrggbb\` (matt wall paint), \`lacquer:#rrggbb\` (satin joinery),
\`stucco:#rrggbb\` (exterior render).
<!-- catalogue:end -->`;
const p = join(ROOT, 'docs', 'SCHEMA.md');
const doc = readFileSync(p, 'utf8');
writeFileSync(p, doc.replace(/<!-- catalogue:start -->[\s\S]*<!-- catalogue:end -->/, text));
console.log(`✓ docs/SCHEMA.md catalogue: ${rows.length} furniture types, ${cars.length} cars, ${MATERIAL_NAMES.length} materials`);
