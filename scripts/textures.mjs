// WebP copies of the photo textures (public/textures/<set>/{diff,nor,rough}.jpg), smaller downloads
// with the JPGs kept as the fallback:
//   <map>.webp      full size, only where it is ≥ 10 % smaller than the JPG at PSNR ≥ 40 dB against
//                   it (visually the same); the lowest quality meeting that is used
//   diff-512.webp   colour map at ≤ 512 px for phones / tablets ('lite' mode), PSNR ≥ 40 dB against
//                   a Lanczos resize
// and engine/texture-files.js listing what exists, read by engine/textures.js.
//
//   npm run textures                  every set
//   node scripts/textures.mjs --set oak   one set (e.g. after adding public/textures/<set>/*.jpg)
// Uses the `sharp` npm package (installed with `npm install`): works the same on Windows, macOS and Linux.
// New sets: put diff.jpg (+ nor.jpg, rough.jpg; CC0 only, credit them in public/textures/CREDITS.md)
// in public/textures/<name>/, register the set in engine/materials.js (SETS + a material), run this.
import { readdirSync, existsSync, statSync, rmSync, writeFileSync, mkdtempSync, readFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'public', 'textures');
const QUALITIES = [95, 92, 90, 88, 85, 82, 80, 78, 75];
const MIN_PSNR = 40, MIN_SAVING = 0.1, LITE = 512;
const only = (() => { const i = process.argv.indexOf('--set'); return i > 0 ? process.argv[i + 1] : null; })();

let sharp;
try { sharp = (await import('sharp')).default; } catch (e) {
  console.log('✗ The "sharp" package is missing: run npm install / paket "sharp" belum ada: jalankan npm install');
  process.exit(1);
}
const tmp = mkdtempSync(join(tmpdir(), 'h3s-webp-'));

async function encode(src, q, out, size = 0) {
  let s = sharp(src);
  if (size) s = s.resize(size, size, { fit: 'inside', withoutEnlargement: true, kernel: 'lanczos3' });
  await s.webp({ quality: q, effort: 6, smartSubsample: true }).toFile(out);
}
async function reference(src, size, out) { // the resized image a lite file is compared with
  return sharp(src).resize(size, size, { fit: 'inside', withoutEnlargement: true, kernel: 'lanczos3' }).png().toFile(out);
}
async function psnr(a, b) {
  const [x, y] = await Promise.all([a, b].map(f => sharp(f).removeAlpha().raw().toBuffer()));
  let se = 0;
  for (let i = 0; i < x.length; i++) { const d = x[i] - y[i]; se += d * d; }
  const mse = se / x.length;
  return mse === 0 ? 99 : 10 * Math.log10(255 * 255 / mse);
}
// lowest quality that keeps PSNR ≥ MIN_PSNR against ref; null when none is small enough
async function best(src, ref, out, maxBytes, size = 0) {
  let pick = null;
  for (const q of QUALITIES) {
    const f = join(tmp, `q${q}.webp`);
    await encode(src, q, f, size);
    const bytes = statSync(f).size, p = await psnr(ref, f);
    if (p < MIN_PSNR) break;
    if (bytes <= maxBytes) pick = { q, bytes, p, f };
  }
  if (pick) writeFileSync(out, readFileSync(pick.f));
  return pick;
}

// keep the entries of the sets not processed this time
const files = {};
try {
  const old = readFileSync(join(ROOT, 'engine', 'texture-files.js'), 'utf8');
  for (const m of old.matchAll(/^  (\w+): (\{.*\}),$/gm)) files[m[1]] = JSON.parse(m[2]);
} catch (e) { /* first run */ }
let jpgBytes = 0, fullBytes = 0, liteBefore = 0, liteAfter = 0;
for (const set of readdirSync(DIR).filter(d => statSync(join(DIR, d)).isDirectory() && (!only || d === only)).sort()) {
  const entry = {};
  for (const map of ['diff', 'nor', 'rough']) {
    const jpg = join(DIR, set, map + '.jpg'), webp = join(DIR, set, map + '.webp');
    if (!existsSync(jpg)) continue;
    const size = statSync(jpg).size;
    jpgBytes += size;
    const pick = await best(jpg, jpg, webp, size * (1 - MIN_SAVING));
    if (pick) entry[map] = 'webp'; else if (existsSync(webp)) rmSync(webp);
    fullBytes += pick ? pick.bytes : size;
    console.log(`${set}/${map}: ${pick ? `webp q${pick.q} ${Math.round(pick.bytes / 1024)} KB (jpg ${Math.round(size / 1024)} KB, ${pick.p.toFixed(1)} dB)` : `jpg ${Math.round(size / 1024)} KB`}`);
    if (map === 'diff') {
      const ref = join(tmp, 'ref.png'), lite = join(DIR, set, `diff-${LITE}.webp`);
      await reference(jpg, LITE, ref);
      const l = await best(jpg, ref, lite, Infinity, LITE);
      liteBefore += size;
      if (l) { entry.lite = true; liteAfter += l.bytes; console.log(`  lite ${LITE}px: q${l.q} ${Math.round(l.bytes / 1024)} KB (${l.p.toFixed(1)} dB)`); }
      else { liteAfter += size; if (existsSync(lite)) rmSync(lite); }
    }
  }
  files[set] = entry;
}
rmSync(tmp, { recursive: true, force: true });

writeFileSync(join(ROOT, 'engine', 'texture-files.js'),
  '// Generated by scripts/textures.mjs (npm run textures): which WebP copies exist per photo set.\n' +
  '// { set: { diff|nor|rough: \'webp\' (else the .jpg), lite: true (diff-512.webp for phones) } }\n' +
  'export const TEXTURE_FILES = {\n' + Object.entries(files).sort((a, b) => (a[0] < b[0] ? -1 : 1)).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},\n`).join('') + '};\n');
const kb = (n) => Math.round(n / 1024) + ' KB';
console.log(`\nfull sets: ${kb(jpgBytes)} jpg → ${kb(fullBytes)}; phone colour maps: ${kb(liteBefore)} → ${kb(liteAfter)}`);
