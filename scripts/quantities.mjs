// Quantity take-off + cost estimate of the active house, for the wizard (Claude reads the JSON).
//   npm run quantities [-- --project <name>]   (or: node scripts/quantities.mjs --project <name>)
// Writes projects/<name>/quantities.json = { quantities, estimate } and prints a short summary.
// The cost page (studio/cost.html) computes the same live in the browser; this file is a snapshot.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildHeadless } from './lib/headless.mjs';

const { dir, built, Z, PROJECT, INTERIOR } = await buildHeadless({ dynamicDoors: true });
const { computeQuantities } = await import('../engine/cost/quantities.js');
const { calc, defaults } = await import('../engine/cost/calc.js');
const { ratesFor, DEFAULT_REGION, RATES, withProject } = await import('../engine/cost/rates/index.js');

const Q = computeQuantities({ Z, PROJECT, INTERIOR, energy: built.energy, trees: built.trees.length });
const regionId = PROJECT.cost?.region || DEFAULT_REGION;
const R = withProject(ratesFor(regionId), PROJECT);
const E = calc(Q, R, defaults(R, PROJECT));
const round = (v) => Math.round(v);
const estimate = {
  region: R.id, quality: E.A.quality, assumptions: E.A, currency: R.currency,
  total: round(E.total), low: round(E.low), high: round(E.high), perM2: round(E.perM2.total),
  construction: round(E.construction), fees: round(E.fees), permits: round(E.permits), contingency: round(E.cont), ppn: round(E.ppn),
  categories: E.cats.map(c => ({ id: c.id, name: c.name.en, total: round(c.total), items: c.items.map(i => ({ id: i.id, name: i.n.en, unit: i.u, qty: Math.round(i.qty * 100) / 100, rate: round(i.rate), amount: round(i.amt) })) })),
  perLevel: Object.fromEntries(Object.entries(E.perLevel).map(([k, v]) => [k, round(v)])),
};
const out = join(dir, 'quantities.json');
writeFileSync(out, JSON.stringify({ note: 'GENERATED by scripts/quantities.mjs — do not edit. ESTIMATE only / PERKIRAAN saja.', quantities: Q, estimate }, null, 1) + '\n');

const idr = (v) => 'Rp ' + Math.round(v / 1e6).toLocaleString('id-ID') + ' jt';
if (!RATES[regionId]) console.log(`! region "${regionId}" has no rate table; used ${R.id} / wilayah belum ada, dipakai ${R.id}`);
console.log(`GFA / luas lantai: ${Q.gfa} m² (${Q.order.map(l => `${l} ${Q.levels[l].area}`).join(', ')}) · roof/atap ${Q.roofs.sloped} m² · PV ${Q.pv.kwp} kWp`);
console.log(`Estimate / perkiraan (${R.name.en}, ${E.A.quality}): ${idr(E.total)} (${idr(E.low)} – ${idr(E.high)}), ±${idr(E.perM2.total)}/m²`);
console.log(`→ ${out}`);
